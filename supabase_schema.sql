-- 1. Tạo bảng lưu thông tin mỗi khi có người nhập dữ liệu
CREATE TABLE IF NOT EXISTS public.student_logins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname TEXT,
    student_code TEXT,
    class_name TEXT,
    batch TEXT,
    program_code TEXT,
    email TEXT,
    balance TEXT,
    login_type TEXT DEFAULT 'feid',
    user_agent TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Kích hoạt Row Level Security (RLS)
ALTER TABLE public.student_logins ENABLE ROW LEVEL SECURITY;

-- 3. Cho phép người dùng từ web (kể cả chưa đăng nhập supabase) gửi thông tin lên (INSERT)
DROP POLICY IF EXISTS "Cho phép khách gửi dữ liệu đăng nhập" ON public.student_logins;
CREATE POLICY "Cho phép khách gửi dữ liệu đăng nhập" 
ON public.student_logins 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- 4. Chỉ cho phép tài khoản quản trị (Supabase Dashboard) đọc xem dữ liệu
DROP POLICY IF EXISTS "Chỉ quản trị viên mới được đọc dữ liệu" ON public.student_logins;
CREATE POLICY "Chỉ quản trị viên mới được đọc dữ liệu" 
ON public.student_logins 
FOR SELECT 
TO authenticated 
USING (true);
